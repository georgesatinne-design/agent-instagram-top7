"""Photographies et documents *réels* exclusivement, depuis Wikimedia Commons.

- PAS de génération d'images, de modèle d'image ni de recherche libre du web.
- Chaque titre de fichier est présélectionné éditorialement dans photos_verifiees.json.
- Le serveur Commons doit confirmer le droit de réutilisation à chaque premier téléchargement.
- En cas d'incertitude sur la licence, l'asset est refusé.
- Le dépôt conserve les preuves de licence et les empreintes SHA256 dans son état interne.
- Image utilisée : photo réelle/scan ancien; habillage graphique réalisé par Pillow.
"""
from __future__ import annotations
import datetime as dt
import hashlib, html, io, json, re
from pathlib import Path
from urllib.parse import urlparse
import requests
from PIL import Image, ImageOps, UnidentifiedImageError
from .catalogue import ROOT, STATE, read, write

API='https://commons.wikimedia.org/w/api.php'
UA='BDEditorialBot/2.0 (Wikimedia Commons non-AI images; contact: repository GitHub)'
CATALOGUE=ROOT/'photos_verifiees.json'
CACHE=STATE/'photos_authentiques'
MAX_BYTES=9_000_000
BAD_SIGNS=re.compile(r'\b(midjourney|dall[ -]?e|stable diffusion|ai[ -]generated|generated by ai|artificial intelligence generated|imagen|text to image)\b',re.I)

class PhotosIndisponibles(RuntimeError):pass

def _license(meta, titre, option):
    """CC0, ou ancien domaine public confirmé *explicitement* pour un document approuvé."""
    info=lambda k: str((meta.get(k) or {}).get('value','')).strip()
    short=html.unescape(re.sub('<[^>]*>','',info('LicenseShortName'))).lower()
    raw=html.unescape(re.sub('<[^>]*>','',info('UsageTerms')+' '+info('License'))).lower()
    copyright=info('Copyrighted').lower()
    if BAD_SIGNS.search(titre+' '+info('ImageDescription')+' '+info('Artist')):
        raise PhotosIndisponibles('Média possiblement généré par IA, rejeté')
    if 'cc0' in short or 'cc-zero' in short or 'cc0' in raw:
        return 'CC0 1.0'
    if option.get('domaine_public_ancien') and ('public domain' in short or 'domaine public' in short or 'pd-old' in short):
        if not option.get('artiste_mort_avant_1900'):raise PhotosIndisponibles('Domaine public historique non étayé')
        return 'Domaine public historique (validé manuellement)'
    raise PhotosIndisponibles('Licence sans crédit obligatoire non prouvée : '+short)

def _valid_image_url(url):
    parsed=urlparse(url)
    if parsed.scheme!='https' or parsed.username or parsed.password or parsed.port not in (None,443):
        return False
    if parsed.hostname=='upload.wikimedia.org':
        return parsed.path.startswith('/wikipedia/')
    if parsed.hostname=='commons.wikimedia.org':
        return parsed.path.startswith('/wiki/Special:Redirect/file/') or parsed.path.startswith('/w/Special:Redirect/file/')
    return False

def _fetch_file(session,titre,option):
    if not re.fullmatch(r'[^<>\x00-\x1f]{6,200}\.(?:jpg|jpeg|png|webp)',titre,re.I):
        raise PhotosIndisponibles('Nom de fichier invalide')
    params={'action':'query','format':'json','formatversion':'2','prop':'imageinfo',
      'iiprop':'url|mime|size|extmetadata','iiurlwidth':1600,'titles':'File:'+titre}
    response=session.get(API,params=params,timeout=18,headers={'User-Agent':UA})
    response.raise_for_status()
    pages=((response.json().get('query') or {}).get('pages') or [])
    if len(pages)!=1 or pages[0].get('missing') or not pages[0].get('imageinfo'):
        raise PhotosIndisponibles('Image Commons non trouvée')
    inf=pages[0]['imageinfo'][0]
    if inf.get('mime') not in ('image/jpeg','image/png','image/webp'):
        raise PhotosIndisponibles('Image non raster')
    licence=_license(inf.get('extmetadata') or {},titre,option)
    url=inf.get('thumburl') or inf.get('url') or ''
    if not _valid_image_url(url):raise PhotosIndisponibles('URL média hors Wikimedia: domaine non approuvé')
    r=session.get(url,timeout=24,headers={'User-Agent':UA},stream=True)
    try:
        r.raise_for_status()
        if not _valid_image_url(r.url):raise PhotosIndisponibles('Redirection média hors Wikimedia')
        if not r.headers.get('Content-Type','').lower().startswith('image/'):
            raise PhotosIndisponibles('Téléchargement non image')
        size=0;buffers=[]
        for block in r.iter_content(64*1024):
            size+=len(block)
            if size>MAX_BYTES:raise PhotosIndisponibles('Photo trop volumineuse')
            buffers.append(block)
        data=b''.join(buffers)
    finally:
        r.close()
    if len(data)<12_000:raise PhotosIndisponibles('Photo trop petite ou invalide')
    with Image.open(io.BytesIO(data)) as src:
        if src.width<340 or src.height<340 or src.width*src.height>55_000_000:
            raise PhotosIndisponibles('Photo de dimensions insuffisantes ou excessives')
        im=ImageOps.exif_transpose(src).convert('RGB')
        im.thumbnail((1800,1800),Image.Resampling.LANCZOS)
        bio=io.BytesIO();im.save(bio,'JPEG',quality=87,optimize=True)
    clean=bio.getvalue()
    metadata=inf.get('extmetadata') or {}
    get=lambda key:html.unescape(re.sub(r'<[^>]*>','',str((metadata.get(key) or {}).get('value','')))).strip()[:300]
    return clean,{'titre_commons':titre,'fichier_source':'https://commons.wikimedia.org/wiki/File:'+titre.replace(' ','_'),
        'image_url':url,'licence':licence,'auteur':get('Artist'),'description':get('ImageDescription'),
        'sha256':hashlib.sha256(clean).hexdigest(),'telecharge_le':dt.datetime.now(dt.timezone.utc).isoformat(),
        'IA_generee':False,'adaptation':'recadrage et composition graphique (aucune image synthétique)'}

def resolve(fact,*,session=None,cache=None):
    """Retourne (chemins des photos locales, licences) ou lève PhotosIndisponibles.

    Pas d'illustration de remplacement inventée; pas de banque de photos aléatoires.
    """
    session=session or requests.Session();cache=Path(cache or CACHE)
    choices=(read(CATALOGUE,{}) or {}).get('groupes',{})
    groupe=next((name for name in choices if fact['id'].startswith(name)),None)
    if not groupe:raise PhotosIndisponibles('Aucune photo authentique préapprouvée pour '+fact['id'])
    options=choices[groupe]['photos'];folder=cache/groupe;folder.mkdir(parents=True,exist_ok=True)
    files=[];proofs=[];errors=[]
    for idx,op in enumerate(options):
        dest=folder/f'photo_{idx:02d}.jpg';audit=folder/f'photo_{idx:02d}.json'
        try:
            if dest.is_file() and audit.is_file():
                meta=read(audit,{})
                if (meta.get('titre_commons')==op['titre'] and meta.get('licence') and
                    meta.get('sha256')==hashlib.sha256(dest.read_bytes()).hexdigest()):
                    files.append(dest);proofs.append(meta);continue
            blob,meta=_fetch_file(session,op['titre'],op)
            dest.write_bytes(blob);write(audit,meta)
            files.append(dest);proofs.append(meta)
        except (requests.RequestException,PhotosIndisponibles,ValueError,OSError,UnidentifiedImageError) as exc:
            errors.append(op['titre']+': '+str(exc)[:140])
    if len(files)<1:
        raise PhotosIndisponibles(f'Au moins 1 photo authentique requise pour {groupe}; aucune obtenue. '+ '; '.join(errors)[:340])
    # Une seule photographie réelle peut être exploitée de plusieurs façons : cadrages,
    # zooms, diptyques et typographie, sans créer de faux visuels.
    return files,proofs
