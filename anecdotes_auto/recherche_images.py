# Curated facts may have an independently written scenario. For facts not present,
# we use ONLY the group-level scene vocabulary above, never a random stock-photo query.
BLOCKED_KEYS = ('ai-generated','ai generated','ai-assisted','ai assisted','generative ai',
                'artificial intelligence generated','generated by ai','created with ai',
                'midjourney','stable diffusion','dall-e','nightcafe','ideogram',
                'text-to-image','text to image','synthetic image')
FILE_EXT = re.compile(r'\.(jpe?g|png|webp)$', re.I)


def norm(text):
    s=unicodedata.normalize('NFKD',str(text or '').lower())
    return ''.join(c for c in s if not unicodedata.combining(c))


def clean(text):
    return html.unescape(re.sub('<[^>]+>',' ',str(text or ''))).strip()


def _anchor_match(blob,aliases):
    normal=norm(blob)
    return any(norm(a) in normal for a in aliases if len(a)>3)


def _field(meta,key):
    raw=(meta or {}).get(key) or {}
    return clean(raw.get('value','') if isinstance(raw,dict) else raw)


def _commons_results(query,session,*,limit=18):
    params={'action':'query','format':'json','formatversion':'2','generator':'search',
            'gsrsearch':query,'gsrnamespace':6,'gsrlimit':limit,
            'prop':'imageinfo','iiprop':'mime|size|extmetadata|url','iiurlwidth':1400}
    r=session.get(COMMONS_API,params=params,headers={'User-Agent':UA},timeout=18)
    r.raise_for_status()
    pages=(r.json().get('query') or {}).get('pages') or []
    results=[]
    for p in pages:
        title=str(p.get('title',''))
        info=(p.get('imageinfo') or [{}])[0]
        meta=info.get('extmetadata') or {}
        if not title.startswith('File:') or not FILE_EXT.search(title):continue
        if info.get('mime') not in ('image/jpeg','image/png','image/webp'):continue
        desc=_field(meta,'ImageDescription')
        lic=norm(_field(meta,'LicenseShortName')+' '+_field(meta,'UsageTerms'))
        if not ('cc0' in lic or 'cc-zero' in lic or 'public domain' in lic or 'domaine public' in lic):continue
        results.append({'provider':'commons','title':title[5:],'description':desc,
                        'meta_text':title+' '+desc,'license_label':lic.strip(),'creator':_field(meta,'Artist'),
                        'url':info.get('thumburl') or info.get('url'),
                        'page_url':'https://commons.wikimedia.org/wiki/'+title.replace(' ','_')})
    return results


def _openverse_results(query,session,*,limit=20):
    # Une recherche de secours, JAMAIS preuve unique d'une licence.
    r=session.get(OPENVERSE_API,params={'q':query,'license':'cc0,pdm','page_size':limit},
                  headers={'User-Agent':UA},timeout=16)
    r.raise_for_status()
    out=[]
    for obj in (r.json().get('results') or []):
        lic=str(obj.get('license','')).lower()
        if lic not in ('cc0','pdm') or obj.get('mature'):continue
        url=str(obj.get('url') or '');landing=str(obj.get('foreign_landing_url') or '')
        if not url.startswith('https://') or not landing.startswith('https://'):continue
        # Recherche transversale; la source d'origine doit rester vérifiable.
        out.append({'provider':'openverse','title':str(obj.get('title') or ''),
            'description':' '.join(str(t.get('name') or '') for t in obj.get('tags') or [] if isinstance(t,dict)),
            'meta_text':str(obj.get('title') or '')+' '+' '.join(str(t.get('name') or '') for t in obj.get('tags') or [] if isinstance(t,dict)),
            'url':url,'page_url':landing,'license_label':lic.strip(),
            'license_url':str(obj.get('license_url') or ''),'creator':str(obj.get('creator') or ''),
            'source':str(obj.get('provider') or ''),'id':str(obj.get('id') or '')})
    return out


def _loc_results(query,session,*,limit=20):
    r=session.get(LOC_API,params={'fo':'json','q':query,'c':limit},
                  headers={'User-Agent':UA},timeout=16)
    r.raise_for_status()
    out=[]
    for item in (r.json().get('results') or []):
        rights=' '.join(str(item.get(k) or '') for k in ('rights','rights_and_access','rights_advisory'))
        # "No known restrictions" alone is NOT proof of public-domain status.
        if 'public domain' not in norm(rights) or 'restricted' in norm(rights):continue
        imgs=item.get('image_url') or []
        img=imgs[-1] if isinstance(imgs,list) and imgs else imgs if isinstance(imgs,str) else ''
        if not img or not str(img).startswith('https://'):continue
        out.append({'provider':'loc','title':str(item.get('title') or ''),
          'description':' '.join(item.get('subject') or []) if isinstance(item.get('subject'),list) else str(item.get('description') or ''),
          'meta_text':str(item.get('title') or '')+' '+str(item.get('subject') or ''),
          'url':img,'page_url':str(item.get('id') or ''),'license_label':'public domain explicit','license_url':'',
          'creator':'Library of Congress'})
    return out


def _safe_image_url(url,provider):
    try:
        p=urlparse(url)
        if p.scheme!='https' or p.username or p.password or p.port not in (None,443):return False
        host=p.hostname or ''
        if provider=='commons':return _valid_image_url(url)
        if provider=='openverse':
            return host in {'live.staticflickr.com','farm.staticflickr.com','cdn.stocksnap.io','images.pexels.com','upload.wikimedia.org','thumb.wikimedia.org'}
        if provider=='loc':return host in {'www.loc.gov','loc.gov','cdn.loc.gov','tile.loc.gov','tile.loc.gov'}
        return False
    except (ValueError,TypeError):return False


def _verify_external_license(item,session):
    if item['provider']=='loc':
        return item['license_label']=='public domain explicit' and item['page_url'].startswith('https://www.loc.gov/')
    if item['provider']!='openverse':return False
    lic=item['license_label'];landing=item['page_url']
    host=urlparse(landing).hostname or ''
    # Wikimedia hosted assets are always re-resolved via the Commons original API.
    if host=='commons.wikimedia.org':return False
    if lic!='cc0':return False
    if not item.get('license_url','').startswith('https://creativecommons.org/publicdomain/zero/'):
        return False
    if host not in {'www.flickr.com','flickr.com','stocksnap.io','www.stocksnap.io','www.pexels.com','pexels.com'}:
        return False
    # Independent origin-page check. Failure means no use; Openverse alone is not proof.
    try:
        r=session.get(landing,headers={'User-Agent':UA},timeout=13,allow_redirects=False)
        r.raise_for_status()
        if urlparse(r.url).hostname != host or len(r.content)>1_500_000:return False
        body=norm(r.text)
        return bool('cc0' in body or 'cc zero' in body or 'creative commons zero' in body or 'public domain dedication' in body)
    except requests.RequestException:return False


def _download_external(item,session):
    url=item['url'];provider=item['provider']
    if not _safe_image_url(url,provider):raise PhotosIndisponibles('Origine image hors liste autorisée')
    if not _verify_external_license(item,session):raise PhotosIndisponibles('Licence à la source non confirmée')
    r=session.get(url,timeout=23,stream=True,headers={'User-Agent':UA},allow_redirects=False)
    try:
        r.raise_for_status()
        if not _safe_image_url(r.url,provider):raise PhotosIndisponibles('Redirection interdite')
        if not str(r.headers.get('Content-Type','')).startswith('image/'):
            raise PhotosIndisponibles('Média non image')
        size=0;chunks=[]
        for part in r.iter_content(65536):
            size+=len(part)
            if size>10_000_000:raise PhotosIndisponibles('Média trop lourd')
            chunks.append(part)
        data=b''.join(chunks)
    finally:r.close()
    with Image.open(io.BytesIO(data)) as raw:
        if min(raw.size)<420 or raw.width*raw.height>55_000_000:
            raise PhotosIndisponibles('Définition image incompatible')
        img=ImageOps.exif_transpose(raw).convert('RGB')
        img.thumbnail((1800,1800),Image.Resampling.LANCZOS)
        out=io.BytesIO();img.save(out,'JPEG',quality=89,optimize=True)
    return out.getvalue(),{
      'titre_commons':item['title'],'url_commons':item['page_url'],'image_url':url,
      'licence':'CC0 1.0' if provider=='openverse' else 'Public domain explicit',
      'auteur':item.get('creator',''),'description':item.get('description','')[:400],
      'date_collecte':dt.datetime.now(dt.timezone.utc).isoformat(),'illustration_IA':False,
      'provider':provider}


def _file_from_candidate(item,session,cache):
    if item['provider']=='commons':
        title=item['title']
        key=hashlib.sha256(('commons:'+title).encode()).hexdigest()[:24]
        file=cache/(key+'.jpg');proof_file=cache/(key+'.json')
        if file.is_file() and proof_file.is_file():
            meta=read(proof_file,{})
            if meta.get('sha256')==hashlib.sha256(file.read_bytes()).hexdigest() and meta.get('licence'):
                return file,meta
        # This checks Commons metadata afresh before first download.
        # Les reproductions d'oeuvres de Rodolphe Töpffer sont aussi
        # éligibles lorsqu'il EST identifié comme artiste sur la notice Commons.
        artist=norm(item.get('creator',''))
        old_work=('topffer' in artist) and ('public domain' in item.get('license_label',''))
        blob,meta=_fetch_file(session,title,{'domaine_public_ancien':old_work,
                                             'artiste_mort_avant_1900':old_work})
    else:
        key=hashlib.sha256((item['provider']+':'+item['page_url']).encode()).hexdigest()[:24]
        file=cache/(key+'.jpg');proof_file=cache/(key+'.json')
        if file.is_file() and proof_file.is_file():
            meta=read(proof_file,{})
            if meta.get('sha256')==hashlib.sha256(file.read_bytes()).hexdigest() and meta.get('licence'):
                return file,meta
        blob,meta=_download_external(item,session)
    meta['sha256']=hashlib.sha256(blob).hexdigest()
    file.write_bytes(blob);write(proof_file,meta)
    return file,meta


def _match_candidate(candidate,scene):
    page,role,query,must,secondary=scene
    blob=clean(candidate['meta_text'])
    if any(bad in norm(blob) for bad in BLOCKED_KEYS):return False
    if not _anchor_match(blob,must):return False
    # Preserve relevance; query-ranked results cannot stand in for exact metadata.
    if not _anchor_match(blob,secondary):return False
    # For group-specific contextual shots, no photograph is labelled archival
    # without date provenance. Role names explicitly say "AUJOURD HUI".
    return True


def _cached_search(provider,query,session,cache):
    key=hashlib.sha256((provider+'|'+query).encode()).hexdigest()[:24]
    path=cache/'recherches'/(key+'.json')
    saved=read(path,{}) or {}
    if saved.get('when'):
        try:
            age=dt.datetime.now(dt.timezone.utc)-dt.datetime.fromisoformat(saved['when'])
            if age.total_seconds()<24*3600:return saved.get('results',[])
        except ValueError:pass
    global _requetes_faites
    if _requetes_faites>=REQUETES_MAX_PAR_EXECUTION:
        raise PhotosIndisponibles('Budget de recherches atteint; continuer au prochain lancement')
    _requetes_faites+=1
    if provider=='commons':out=_commons_results(query,session)
    elif provider=='openverse':out=_openverse_results(query,session)
    else:out=_loc_results(query,session)
    write(path,{'when':dt.datetime.now(dt.timezone.utc).isoformat(),'results':out})
    return out


def discover(fact,*,session=None,cache=None,existing_proofs=(),min_required=3,budget=12):
    """A new image is never added merely to fill space.

    Queries search the described real subject, record page-specific relevance,
    validate external rights and reject perceptual duplicates before selection.
    """
    session=session or requests.Session();cache=Path(cache or CACHE)
    cache.mkdir(parents=True,exist_ok=True)
    prefix=fact['id'].split('-')[0]
    scenes=SCENES.get(fact['id']) or SCENES.get(prefix)
    if not scenes:raise PhotosIndisponibles('Sujet sans plan de recherche photographique précis: '+prefix)
    selected=[];proofs=[];hashes=[];origins=set();logs=[]
    for page,role,query,must,secondary in scenes:
        ok=False
        # independent source paths; Openverse and LoC may return no results or 403
        for provider in ('commons','openverse','loc'):
            if budget<=0:break
            budget-=1
            try:results=_cached_search(provider,query,session,cache)
            except (requests.RequestException,ValueError,KeyError) as exc:
                logs.append(f'{provider} p{page}: {type(exc).__name__}');continue
            # Favor title, specific place and enough detail (without search-engine inventing proof).
            candidates=[x for x in results if _match_candidate(x,(page,role,query,must,secondary))]
            candidates.sort(key=lambda x: (int(_anchor_match(x['title'],must)),
                                           int(x['provider']=='commons')),reverse=True)
            for cand in candidates[:8]:
                try:
                    image_path,meta=_file_from_candidate(cand,session,cache)
                    origin=meta.get('url_commons') or cand.get('page_url')
                    fingerprint=_phash(image_path)
                    if origin in origins or any((fingerprint^h).bit_count()<=6 for h in hashes):
                        continue
                    proof={**meta,'page':page,'role':role,
                       'pertinence':f'Photographie retrouvée sur le sujet « {query} » ; relation confirmée dans son titre/description.',
                       'epoque':'contemporaine' if 'AUJOURD HUI' in role else 'non attestée',
                       'famille_source':origin,'fact_id':fact['id'],'intention_editoriale':fact.get('hook','')}
                    selected.append(image_path);proofs.append(proof);hashes.append(fingerprint)
                    origins.add(origin);ok=True;break
                except (PhotosIndisponibles,requests.RequestException,OSError,ValueError,KeyError) as exc:
                    logs.append(f'{provider} p{page}: {type(exc).__name__} {str(exc)[:65]}')
            if ok:break
        if not ok:logs.append(f'p{page}: image pertinente introuvable')
    if len(selected)<min_required or 1 not in [p['page'] for p in proofs]:
        raise PhotosIndisponibles(f'Photothèque multi-sources insuffisante pour {fact["id"]}: '
           f'{len(selected)}/{min_required} photographies distinctes ; '+ ' | '.join(logs)[:420])
    return selected,proofs


def resolve_avance(fact,*,session=None,cache=None):
    """Conserve les scènes vérifiées puis active une recherche multi-sources.

    If a curated scenario is incomplete, the system does not publish it; an
    independently verified alternative is searched and audited separately.
    """
    from .photos_reelles import resolve as resolve_curated
    old_problem=''
    try:
        return resolve_curated(fact,session=session,cache=cache)
    except PhotosIndisponibles as exc:
        old_problem=str(exc)
    try:
        return discover(fact,session=session,cache=cache)
    except PhotosIndisponibles as exc:
        raise PhotosIndisponibles('Scènes approuvées: '+old_problem[:180]+' ; recherche 3 sources: '+str(exc)[:450]) from exc
